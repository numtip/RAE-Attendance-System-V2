// Synthetic records only; requires a disposable migrated database.
const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
process.env.JWT_SECRET = process.env.JWT_SECRET || 'synthetic-test-secret';
const jwt = require('jsonwebtoken');
const { createApp } = require('../src/app');
const { getPool, closePool } = require('../src/db/pool');
const { createMariaDbRepositories } = require('../src/repositories/mariadbRepositories');
const { createHipUploadService } = require('../src/services/hipUploadService');
const { createHolidayManagementService } = require('../src/services/holidayManagementService');
const { backupBeforeWrite } = require('../src/services/productionBackup');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { gunzipSync } = require('node:zlib');

test('owner HIP preview, replay, holiday approval and removal on MariaDB', { skip: process.env.RUN_MARIADB_TESTS !== '1' }, async (t) => {
  const config = require('../src/config');
  const pool = getPool(config.database);
  const repositories = createMariaDbRepositories();
  const container = { config, repositories, dataSource: 'mariadb' };
  const backupDir = await fs.mkdtemp(path.join(os.tmpdir(), 'rae-backup-test-'));
  const previousBackupDir = process.env.ATTENDANCE_BACKUP_DIR;
  process.env.ATTENDANCE_BACKUP_DIR = backupDir;
  await backupBeforeWrite({ config: { ...config, app: { ...config.app, env: 'production' } } });
  const backupFiles = await fs.readdir(backupDir);
  assert.equal(backupFiles.length, 1);
  assert.match(gunzipSync(await fs.readFile(path.join(backupDir, backupFiles[0]))).toString(), /attendance_holiday/);
  await fs.rm(backupDir, { recursive: true });
  if (previousBackupDir === undefined) delete process.env.ATTENDANCE_BACKUP_DIR;
  else process.env.ATTENDANCE_BACKUP_DIR = previousBackupDir;
  const uid = randomUUID(); const tag = uid.slice(0, 8); const code = `H${tag}`;
  const auth = { employeeUid: uid, role: 'EXECUTIVE' };
  let backups = 0;
  const backup = async () => { backups += 1; };
  const upload = createHipUploadService(container, backup);
  const holidays = createHolidayManagementService(container, backup);
  const csv = `รหัสที่เครื่อง,วัน/เวลา,เข้า [1],ออก [1]\n${code},24/11/2569,08:41,16:35`;
  let holidayId; const batchIds = [];
  t.after(async () => {
    if (holidayId) await pool.query('DELETE FROM attendance_holiday WHERE id=?', [holidayId]);
    await pool.query('DELETE FROM attendance_events WHERE employee_uid=?', [uid]);
    await pool.query('DELETE FROM daily_attendance WHERE employee_uid=?', [uid]);
    await pool.query('DELETE FROM monthly_summary WHERE employee_uid=?', [uid]);
    await pool.query('DELETE FROM staging_facescan_raw WHERE facescan_id=?', [code]);
    for (const batchId of batchIds) await pool.query('DELETE FROM facescan_import_batches WHERE batch_uid=?', [batchId]);
    await pool.query('DELETE FROM employee_identifier WHERE employee_uid=?', [uid]);
    await pool.query('DELETE FROM authorization_grants WHERE employee_uid=?', [uid]);
    await pool.query('DELETE FROM employees WHERE employee_uid=?', [uid]);
    await closePool();
  });
  await pool.query(`INSERT INTO employees (employee_uid, employee_id, first_name_th, last_name_th, email, department,
    employee_type, status, role, login_attempts, created_at, updated_at)
    VALUES (?, ?, 'Test', 'Person', ?, 'Test', 'university', 'active', 'executive', 0, NOW(), NOW())`, [uid, code, `${tag}@example.invalid`]);
  await pool.query(`INSERT INTO employee_identifier (employee_uid,id_type,id_value,source_system,is_primary,status,created_at,updated_at)
    VALUES (?,'facescan_id',?,'test',0,'active',NOW(),NOW())`, [uid, code]);
  await pool.query("INSERT INTO authorization_grants (employee_uid,role,scope_type,created_at,updated_at) VALUES (?,'EXECUTIVE','organization',NOW(),NOW())", [uid]);
  await assert.rejects(() => upload.preview({ ...auth, role: 'EMPLOYEE' }, { csv }), { code: 'FORBIDDEN' });
  const preview = await upload.preview(auth, { csv });
  assert.equal(preview.newResolved, 2);
  assert.equal(backups, 0);
  const server = createApp({ container }).listen(0, '127.0.0.1');
  await new Promise((resolve, reject) => { server.once('listening', resolve); server.once('error', reject); });
  t.after(() => new Promise((resolve) => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}/api/v1/attendance/hip/preview`;
  const anonymous = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ csv }) });
  assert.equal(anonymous.status, 401);
  const token = jwt.sign({ role: 'EXECUTIVE', jti: randomUUID() }, config.jwt.secret, { subject: uid, expiresIn: '10m' });
  const response = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` }, body: JSON.stringify({ csv }) });
  assert.equal(response.status, 200);
  assert.equal((await response.json()).data.newResolved, 2);
  const backupFailure = createHipUploadService(container, async () => { throw new Error('backup failed'); });
  await assert.rejects(() => backupFailure.confirm(auth, { csv, confirm: true, contentSha256: preview.contentSha256 }), /backup failed/);
  assert.equal((await upload.preview(auth, { csv })).alreadyImported, 0);
  await assert.rejects(() => upload.confirm(auth, { csv, confirm: true, contentSha256: '0'.repeat(64) }), { code: 'PREVIEW_MISMATCH' });
  const result = await upload.confirm(auth, { csv, confirm: true, contentSha256: preview.contentSha256 });
  batchIds.push(result.batch.id);
  assert.equal(result.complete, true);
  assert.deepEqual(result.rows, { resolved: 2 });
  const replay = await upload.confirm(auth, { csv, confirm: true, contentSha256: preview.contentSha256 });
  batchIds.push(replay.batch.id);
  assert.deepEqual(replay.rows, { duplicate: 2 });
  assert.equal(replay.derive.employeeDays, 1);
  const history = await upload.history(auth);
  assert.ok(history.length >= 2);
  const [[before]] = await pool.query('SELECT status, late_minutes FROM daily_attendance WHERE employee_uid=? AND date=?', [uid, '2026-11-24']);
  assert.equal(before.status, 'late');
  await holidays.change(auth, null, { date: '2026-11-24', name: 'Synthetic holiday', status: 'approved', sourceReference: 'https://example.invalid/notice' });
  const list = await holidays.list(auth, 2026);
  holidayId = list.find((row) => row.name === 'Synthetic holiday').id;
  const [[during]] = await pool.query('SELECT status, late_minutes FROM daily_attendance WHERE employee_uid=? AND date=?', [uid, '2026-11-24']);
  assert.equal(during.status, 'holiday');
  assert.equal(during.late_minutes, 0);
  const [[monthly]] = await pool.query('SELECT expected_working_days FROM monthly_summary WHERE employee_uid=? AND year=2026 AND month=11', [uid]);
  assert.equal(monthly.expected_working_days, 20);
  await holidays.change(auth, holidayId, {}, true);
  holidayId = null;
  const [[after]] = await pool.query('SELECT status, late_minutes FROM daily_attendance WHERE employee_uid=? AND date=?', [uid, '2026-11-24']);
  assert.equal(after.status, 'late');
  assert.equal(after.late_minutes, 11);
  assert.equal(backups, 4);
});
